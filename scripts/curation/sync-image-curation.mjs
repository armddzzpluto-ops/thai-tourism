import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const provinceRoot = path.join(root, "assets", "images", "provinces");
const validationPath = path.join(provinceRoot, "validation-report.json");
const outputPath = path.join(root, "js", "image-curation-data.js");

const readJson = file =>
  JSON.parse(fs.readFileSync(file, "utf8").replace(/^\uFEFF/, ""));

const validation = readJson(validationPath);
const result = {};

for (const row of validation) {
  const slug = String(row.slug || "").trim();
  if (!slug) continue;

  const metadataPath = path.join(provinceRoot, slug, "metadata.json");
  if (!fs.existsSync(metadataPath)) continue;

  const metadata = readJson(metadataPath);
  const attributions = Array.isArray(metadata.attribution)
    ? metadata.attribution.filter(item => String(item.role || "").startsWith("gallery-"))
    : [];
  const galleryImages = Array.isArray(metadata.galleryImages)
    ? metadata.galleryImages
    : [];

  const complete =
    row.status === "complete" &&
    Number(row.fallbackCount) === 0 &&
    galleryImages.length >= 3 &&
    attributions.length >= 3;

  result[slug] = {
    status: complete ? "complete" : String(row.status || "needs-curation"),
    galleryCurated: complete,
    galleryImages: complete ? galleryImages : [],
    galleryCaptions: complete
      ? attributions.map(item => String(item.caption || metadata.province || slug))
      : [],
    attribution: complete
      ? attributions.map(item => ({
          file: item.file,
          caption: item.caption,
          photoCredit: item.photoCredit,
          imageSource: item.imageSource
        }))
      : []
  };
}

const serialized = JSON.stringify(result, null, 2).replace(/</g, "\\u003c");
const output =
  "/* Generated by scripts/curation/sync-image-curation.mjs. Do not edit manually. */\n" +
  "window.IMAGE_CURATION = " + serialized + ";\n";

fs.writeFileSync(outputPath, output, "utf8");

const completed = Object.values(result).filter(item => item.galleryCurated).length;
console.log(`Synced image curation: ${completed}/${validation.length} provinces complete`);
if (completed !== validation.length) {
  console.warn(`Pending provinces: ${validation.length - completed}`);
}
